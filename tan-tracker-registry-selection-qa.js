var TT_SELECTION_QA = await (async () => {
  const checks = [], errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  const ok = (v, s) => { if (!v) throw Error(s); checks.push(s); };
  const go = async (role, extra = "", reload = false) => {
    await page.goto(`http://127.0.0.1:4317/#tan-tracker?role=${role}&tt_screen=list${extra}`);
    if (reload) await page.reload();
    await page.waitForFunction(() => window.TtRegistryPersonal?.isHydrated());
    await page.locator('[data-tt="registry-selection"]').waitFor();
  };
  const select = (id) => page.locator(`#tt-registry-body [data-tt="registry-select"][value="${id}"]`);
  const batch = (mode) => page.locator(`[data-tt="registry-batch"][data-mode="${mode}"]`);
  const confirm = () => page.locator('[data-tt="cleanup-confirm"]').click();
  const cancel = () => page.locator('[data-tt="cleanup-cancel"]').first().click();
  const count = async (n) => {
    const host = page.locator('[data-tt="registry-selection"]');
    if (!n) return !(await host.locator(".tt-registry-selection--active").count()) && !(await host.evaluate((e) => e.classList.contains("tt-registry-selection--active"))) &&
      !(await page.locator('#tt-registry-body [data-tt="registry-select"]:checked').count());
    return (await host.innerText()).includes(`Выбрано: ${n}`) && await host.evaluate((e) => e.classList.contains("tt-registry-selection--active"));
  };

  await go("admin", "", true);
  await select("TT-2026-005").check();
  ok(await count(1) && !await page.locator('[data-tt="detail"]').count(), "select one without entering card");
  ok(await page.locator('[data-tt="registry-select-all"]').evaluate((e) => e.indeterminate), "partial selection is indeterminate");
  ok(await batch("delete").isDisabled(), "received completed track cannot be deleted");
  await select("TT-2026-001").check();
  ok(await count(2), "select several tracks directly");
  await batch("archive").click();
  ok(await page.locator('[data-tt="cleanup-select"]').count() === 2, "confirmation contains exactly chosen IDs");
  ok(await page.locator('[data-tt="cleanup-select"]:checked').count() === 1, "mixed batch preselects only eligible record");
  ok((await page.getByRole("dialog").innerText()).includes("неподходящих: 1"), "mixed batch explains skipped record");
  ok(!await page.locator('[data-tt="cleanup-scope"], [data-tt="cleanup-mode"]').count(), "selected scope cannot silently become entire registry");
  await cancel();
  ok(await count(2) && await select("TT-2026-005").isChecked(), "cancel preserves selection and data");
  await batch("archive").click(); await confirm();
  ok(!await select("TT-2026-005").count() && await count(1), "general archive affects only eligible selected track");
  await page.locator('[data-tt="registry-view-general-archive"]').click();
  ok(await count(0), "archive view switch clears selection");
  await select("TT-2026-005").check(); await batch("restore").click(); await confirm();
  await page.locator('[data-tt="registry-view-main"]').click();
  ok(await select("TT-2026-005").count() === 1, "restore works straight from general archive list");
  await select("TT-2026-001").check(); await batch("delete").click();
  ok(await page.locator('[data-tt="cleanup-confirm"]').isDisabled(), "direct list deletion retains typed confirmation");
  await cancel(); await page.locator('[data-tt="registry-selection-clear"]').click();
  ok(await count(0), "clear selection works");

  await page.locator('[data-tt="search"]').fill("TT-2026-005");
  await page.locator('[data-tt="registry-select-all"]').check();
  ok(await count(1), "select shown respects search");
  await batch("archive").click();
  ok(await page.locator('[data-tt="cleanup-select"]').count() === 1, "filtered select shown never includes hidden records");
  await cancel();
  await page.locator('[data-tt="search"]').fill("TT-2026-001");
  ok(await count(0), "filtered-out selection is dropped");
  await page.locator('[data-tt="search"]').fill("");
  await page.locator('[data-tt="registry-select-all"]').check();
  ok(await count(await page.locator("#tt-registry-body tr").count()), "select all shown uses explicit visible list");
  await page.locator('[data-tt="registry-select-all"]').uncheck();
  ok(await count(0), "uncheck select shown clears all");

  await go("manager", "&tt_emp=m1");
  await select("TT-2026-005").check();
  ok(!await batch("archive").count(), "ordinary participant has no general archival action");
  await batch("personal").click(); await confirm();
  await ttWaitDemoSaveSaved();
  await page.reload(); await page.waitForFunction(() => window.TtRegistryPersonal?.isHydrated());
  await page.locator('[data-tt="registry-view-archived"]').click();
  await select("TT-2026-005").check();
  ok(await batch("personal-restore").isEnabled(), "personal archive survives reload and supports direct restore");
  await batch("personal-restore").click(); await confirm(); await ttWaitDemoSaveSaved();
  await page.locator('[data-tt="registry-view-main"]').click();
  await select("TT-2026-001").check();
  await go("director");
  ok(await count(0), "actor change clears another person's selection");

  await go("manager", "&tt_emp=m1", true);
  await select("TT-2026-001").check(); await batch("delete").click();
  await page.locator('[data-tt="cleanup-delete-ack"]').fill("УДАЛИТЬ");
  await confirm();
  ok(!await select("TT-2026-001").count(), "creator deletes pre-receipt track directly from registry");
  ok(!await page.evaluate(() => TanTrackerPrototype.orders().some(o => o.id === "TT-2026-001")), "deletion is not personal hiding");

  await go("admin", "", true);
  await select("TT-2026-005").check();
  await page.setViewportSize({width:375,height:812});
  const mobile = page.locator('.tt-cards [data-tt="registry-select"][value="TT-2026-005"]');
  ok(await mobile.isChecked() && await mobile.isVisible(), "desktop-to-mobile keeps selection on separate card checkbox");
  await mobile.uncheck();
  await mobile.focus(); await page.keyboard.press("Space");
  ok(await count(1) && !await page.locator('[data-tt="detail"]').count(), "keyboard card selection never opens detail");
  await batch("personal").click();
  await page.screenshot({path:"/tmp/tandoor-selection-mobile-dialog.png"});
  const footer = await page.locator(".tt-cleanup-footer").boundingBox();
  ok(footer && footer.y + footer.height <= 812, "mobile confirmation footer remains accessible");
  await cancel();
  await page.screenshot({path:"/tmp/tandoor-selection-mobile.png"});
  ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "mobile registry has no horizontal overflow");
  await page.setViewportSize({width:1440,height:900});
  ok(await select("TT-2026-005").isChecked(), "mobile-to-desktop selection remains synchronized");
  await page.evaluate(() => document.documentElement.dataset.theme = "dark");
  await page.screenshot({path:"/tmp/tandoor-selection-desktop-dark.png"});
  await page.locator('#tt-registry-body tr[data-tt-open="TT-2026-005"] td:not(.tt-selection-cell)').first().click();
  ok(await page.locator('[data-tt="detail"]').isVisible(), "ordinary row click still opens detail");

  await go("manager", "&tt_act=ext_03", true);
  const ext = page.locator('[data-tt="external-home"] [data-tt="registry-select"][value="TT-2026-005"]');
  await ext.check();
  ok(await count(1) && !await batch("archive").count(), "external limited shell supports own selection only");
  await batch("personal").click(); await confirm();
  await page.locator('[data-tt="registry-view-archived"]').click();
  await ext.check(); await batch("personal-restore").click(); await confirm();
  ok(!await page.locator('[data-tt="cleanup-confirm"]').count(), "external direct archive and restore complete");

  await page.goto("http://127.0.0.1:4317/#tan-tracker?role=admin&tt_screen=list&as_role=manager");
  await page.waitForFunction(() => window.TtRegistryPersonal?.isHydrated());
  ok(!await page.locator('[data-tt="registry-select"], [data-tt="registry-batch"]').count(), "read-only preview has no registry selection controls");
  ok(errors.length === 0, `no page errors (${errors.join(";")})`);
  return {passed:checks.length,checks};
})();
console.log(JSON.stringify(TT_SELECTION_QA,null,2));

-- Additive only. Existing delegation status constraints and approvals remain readable.
ALTER TABLE delegations
  ADD COLUMN IF NOT EXISTS created_by_user_id UUID REFERENCES users(id),
  ADD COLUMN IF NOT EXISTS basis TEXT,
  ADD COLUMN IF NOT EXISTS workflow_state TEXT;
ALTER TABLE delegation_change_requests
  ADD COLUMN IF NOT EXISTS proposed_assistant_user_id UUID REFERENCES users(id),
  ADD COLUMN IF NOT EXISTS basis TEXT,
  ADD COLUMN IF NOT EXISTS workflow_decision TEXT;
ALTER TABLE delegation_change_history
  ADD COLUMN IF NOT EXISTS event_seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  ADD COLUMN IF NOT EXISTS actor_role TEXT,
  ADD COLUMN IF NOT EXISTS actor_name TEXT,
  ADD COLUMN IF NOT EXISTS snapshot JSONB,
  ADD COLUMN IF NOT EXISTS comment TEXT;
CREATE INDEX IF NOT EXISTS delegation_history_order_idx
  ON delegation_change_history(changed_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS delegation_history_sequence_idx
  ON delegation_change_history(delegation_id, changed_at, event_seq);

CREATE TABLE IF NOT EXISTS assistant_assignment_notifications (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  delegation_id UUID NOT NULL REFERENCES delegations(id) ON DELETE CASCADE,
  event_key TEXT NOT NULL,
  kind TEXT NOT NULL,
  title TEXT NOT NULL,
  message TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  read_at TIMESTAMPTZ,
  UNIQUE(user_id, event_key)
);
CREATE INDEX IF NOT EXISTS assistant_assignment_notifications_inbox_idx
  ON assistant_assignment_notifications(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS assistant_assignment_notifications_unread_idx
  ON assistant_assignment_notifications(user_id) WHERE read_at IS NULL;

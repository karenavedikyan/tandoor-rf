const {default:assert}=await import("node:assert/strict");
const {default:fs}=await import("node:fs/promises");
export async function runAssistantReviewQA({browser,origin,shotsDir}){
  if(!/^http:\/\/127\.0\.0\.1:\d+$/.test(origin))throw Error("Local synthetic QA origin required");
  await fs.mkdir(shotsDir,{recursive:true});
  const checks=[],errors=[],contexts=[];
  const ok=(value,label)=>{assert.ok(value,label);checks.push(label);console.log("PASS",label);};
  async function login(role,width=1440){
    const c=await browser.newContext({viewport:{width,height:1000}});contexts.push(c);
    c.setDefaultTimeout(7000);
    c.setDefaultNavigationTimeout(15000);
    const p=await c.newPage();p.on("pageerror",e=>errors.push(e.message));
    await p.goto(origin+"/login");await p.locator("#email").fill("assignment-"+role+"@example.test");
    await p.locator("#password").fill("LocalTestOnly-Assignments2026!");
    await p.getByRole("button",{name:"Войти",exact:true}).click();await p.waitForURL(u=>u.pathname!=="/login");
    await p.goto(origin+"/access");await p.locator("#access-workspace-app .aa-tabs").waitFor();
    return p;
  }
  const close=p=>p.locator('#ar-dialog [data-ar="close"]').first().click();
  try{
    const p=await login("manager");
    await p.getByRole("button",{name:"Оценить работу",exact:true}).click();await p.locator(".ar-table").waitFor();
    ok(await p.locator(".ar-table tbody tr").count()===5,"manager sees only own completed work");
    await p.locator("#assignment-review-obligation").waitFor();
    ok((await p.locator("#assignment-review-obligation").textContent()).includes("2"),"two mandatory reviews remain");
    ok(await p.locator("#an-bell").count()===1,"one shared notification bell");
    await p.locator("#an-bell").click();await p.locator(".an-item").first().waitFor();
    ok(await p.locator("#an-inbox").evaluate(e=>e.open),"notification drawer is a native modal");
    await p.getByRole("button",{name:"Непрочитанные",exact:true}).click();
    await p.locator('[data-an="unread"][aria-pressed="true"]').waitFor();
    await p.getByRole("button",{name:"Прочитать все",exact:true}).click();await p.locator(".an-empty").waitFor();
    ok((await p.locator(".an-empty").textContent()).includes("прочитаны"),"read-all empties unread filter");
    await p.keyboard.press("Escape");
    ok(await p.locator("#assignment-review-obligation").isVisible(),"reading all does not clear required feedback");
    await p.getByRole("link",{name:"Поставить оценку",exact:true}).click();await p.locator("#ar-dialog").waitFor();
    ok(await p.locator("#ar-star-input button svg").count()===5,"five SVG star inputs");
    const text="Работа выполнена хорошо. <script>window.__reviewInjected=true</script> Клиенты возвращены с итогами.";
    await p.locator("#ar-comment").fill(text);await p.getByRole("button",{name:"Отправить оценку",exact:true}).click();
    ok((await p.locator("#ar-error").textContent()).includes("Выберите"),"no-score submission is rejected");
    await p.getByRole("button",{name:"4 из 5: Хорошо",exact:true}).hover();
    ok(await p.locator("#ar-star-input .ar-on").count()===4,"hover previews four stars");
    await p.getByRole("button",{name:"4 из 5: Хорошо",exact:true}).click();await p.keyboard.press("ArrowRight");
    ok(await p.getByRole("button",{name:"5 из 5: Отлично",exact:true}).getAttribute("aria-pressed")==="true","keyboard chooses next score");
    await close(p);
    ok((await p.locator("#assignment-review-obligation").textContent()).includes("2"),"leaving form does not close work");
    await p.getByRole("link",{name:"Поставить оценку",exact:true}).click();await p.locator("#ar-dialog").waitFor();
    await p.getByRole("button",{name:"4 из 5: Хорошо",exact:true}).click();
    await p.getByRole("button",{name:"Отправить оценку",exact:true}).click();
    ok(await p.locator("#ar-dialog").isVisible(),"no-comment submission stays on form");
    await p.locator("#ar-comment").fill(text);
    await p.screenshot({path:shotsDir+"/manager-star-form-light.png",animations:"disabled"});
    await p.setViewportSize({width:375,height:812});
    ok(await p.locator("#ar-star-input").evaluate(e=>e.getBoundingClientRect().right<=innerWidth),"stars fit mobile");
    await p.screenshot({path:shotsDir+"/manager-star-form-mobile.png",animations:"disabled"});
    await p.getByRole("button",{name:"Отправить оценку",exact:true}).scrollIntoViewIfNeeded();
    ok(await p.locator("#ar-dialog").evaluate(e=>e.scrollTop>0),"mobile form scrolls to submit");
    await p.route("**/api/access/delegations/*/review",async route=>{
      if(route.request().method()==="POST")await route.fulfill({status:503,contentType:"application/json",body:JSON.stringify({error:{message:"Тестовая временная ошибка. Повторите попытку."}})});
      else await route.continue();
    });
    await p.getByRole("button",{name:"Отправить оценку",exact:true}).click();
    await p.locator("#ar-error").filter({hasText:"Тестовая"}).waitFor();
    ok(await p.locator("#ar-comment").inputValue()===text,"failed save preserves typed feedback");
    await p.unroute("**/api/access/delegations/*/review");
    await p.getByRole("button",{name:"Отправить оценку",exact:true}).click();
    await p.locator("#ar-dialog").waitFor({state:"detached"});
    await p.locator("#assignment-review-obligation").filter({hasText:"1"}).waitFor();
    ok(true,"retry saves feedback and clears only one obligation");
    const rated=p.locator(".ar-table tr").filter({hasText:"№b3100001"});
    ok((await rated.textContent()).includes("Закрыто с оценкой"),"real API result updates closure state");
    await rated.getByRole("button",{name:"Посмотреть",exact:true}).click();
    await p.locator(".ar-result").waitFor();
    ok(await p.locator(".ar-comment").textContent()===text,"saved comment renders literally without HTML execution");
    ok(await p.evaluate(()=>window.__reviewInjected===undefined),"adversarial markup does not execute");
    await p.getByText("Клиенты на момент оценки",{exact:true}).click();
    ok(await p.locator(".ar-result li").count()===12,"review includes realistic authorized snapshot");
    await close(p);await p.reload();await p.locator(".ar-table").waitFor();
    await p.locator(".ar-result").waitFor();await close(p);
    ok(await p.locator(".ar-table tr").filter({hasText:"№b3100001"}).locator('.ar-stars[aria-label="4.0 из 5"]').count()===1,"stars persist after page reload");
    await p.locator('#ar-filters [name="status"]').selectOption("required");
    await p.locator("#ar-filters").getByRole("button",{name:"Применить",exact:true}).click();
    await p.locator('#aa-view[aria-busy="true"]').waitFor({state:"detached"});
    await p.locator(".ar-table tbody tr").filter({hasText:"№b3100007"}).waitFor();
    ok(await p.locator(".ar-table tbody tr").count()===1,"mandatory-only filter");
    await p.getByRole("button",{name:"Сбросить фильтры",exact:true}).click();
    await p.locator(".ar-table tr").filter({hasText:"№b3100001"}).waitFor();
    await p.locator('#ar-filters [name="q"]').fill("нет-таких-сотрудников");
    await p.locator("#ar-filters").getByRole("button",{name:"Применить",exact:true}).click();
    await p.getByText("Завершённые назначения с такими условиями не найдены.",{exact:true}).waitFor();
    ok(true,"search has a readable empty state");
    await p.getByRole("button",{name:"Сбросить фильтры",exact:true}).click();
    await p.locator(".ar-table tr").filter({hasText:"№b3100001"}).waitFor();
    await p.setViewportSize({width:1440,height:1000});
    await p.getByRole("button",{name:"Назначения",exact:true}).click();await p.locator("#aa-list-data table").waitFor();
    await p.getByRole("button",{name:"На весь экран",exact:true}).click();
    ok(await p.locator(".aa-fullscreen").count()===1,"existing fullscreen assignments still work");
    await p.keyboard.press("Escape");
    const leader=await login("coordinator");
    await leader.getByRole("button",{name:"Оценки ассистентов",exact:true}).click();await leader.locator(".ar-assistants article").first().waitFor();
    ok(await leader.locator(".ar-assistants article").count()===2,"ROA sees both assistants");
    await leader.locator("#an-bell").click();await leader.locator(".an-item").first().waitFor();
    await leader.screenshot({path:shotsDir+"/roa-notifications-desktop.png",animations:"disabled"});
    const alert=leader.locator(".an-item").filter({hasText:"Получена оценка работы ассистента"}).first();
    await alert.getByRole("link",{name:"Посмотреть оценку",exact:true}).click();await leader.locator(".ar-result").waitFor();
    ok(await leader.locator("#ar-star-input").count()===0,"ROA notification opens read-only score");
    await close(leader);
    const director=await login("director");
    await director.getByRole("button",{name:"Оценки ассистентов",exact:true}).click();await director.locator(".ar-table").waitFor();
    ok(await director.locator('[data-ar="open"].aa-primary').count()===0,"director cannot rate on behalf of manager");
    await director.locator('#ar-filters [name="score"]').selectOption("low");
    await director.locator("#ar-filters").getByRole("button",{name:"Применить",exact:true}).click();
    await director.locator('#aa-view[aria-busy="true"]').waitFor({state:"detached"});
    await director.locator('.ar-table .ar-stars[aria-label="2.0 из 5"]').waitFor();
    ok(await director.locator(".ar-table tbody tr").count()===2,"director low-score filter");
    await director.getByRole("button",{name:"Включить тёмную тему",exact:true}).click();
    await director.setViewportSize({width:375,height:812});await director.locator(".ar-assistants").scrollIntoViewIfNeeded();
    await director.screenshot({path:shotsDir+"/director-summary-mobile-dark.png",animations:"disabled"});
    ok(await director.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),"dark mobile overview has no page overflow");
    const assistant=await login("assistant");
    ok(await assistant.getByRole("button",{name:"Оценки ассистентов",exact:true}).count()===0,"assistant has no rating tab");
    await assistant.locator("#an-bell").click();await assistant.locator(".an-item").first().waitFor();
    ok(!(await assistant.locator("#an-inbox").textContent()).includes("оценк"),"assistant inbox contains no review events");
    await assistant.getByRole("link",{name:"Открыть клиентов",exact:true}).click();
    await assistant.waitForURL(u=>u.pathname==="/clients");await assistant.locator(".clients-page-title").waitFor();
    ok(await assistant.locator("#an-bell").count()===1,"same bell on assistant client directory");
    await assistant.locator("#clients-table-body .clients-link").first().waitFor();
    ok(await assistant.locator("#clients-table-body .clients-link").count()>0,"assistant receives a realistic restricted client registry");
    await assistant.locator("#v3-focus-enter-btn").click();await assistant.locator("body.x14-focus-mode").waitFor();
    ok(await assistant.locator("#v3-focus-exit").isVisible(),"assistant keeps the common fullscreen client registry");
    await assistant.keyboard.press("Escape");await assistant.locator("body.x14-focus-mode").waitFor({state:"detached"});
    await leader.goto(origin+"/access?assignment=b3100008-0000-4000-8000-000000000008");
    await leader.getByRole("button",{name:"Отозвать доступ",exact:true}).click();
    await leader.locator("#aa-decision-reason").fill("Тест: согласованное досрочное завершение работы.");
    const revoked=leader.waitForResponse(r=>r.url().endsWith("/revoke")&&r.request().method()==="POST");
    await leader.getByRole("button",{name:"Подтвердить",exact:true}).click();
    ok((await revoked).status()===200,"existing ROA revoke flow still works");
    const refreshed=assistant.waitForResponse(r=>r.url().includes("/api/clients/v3/list")&&r.request().method()==="GET");
    await assistant.locator("#an-bell").click();
    ok((await(await refreshed).json()).total===0,"notification scope revision reloads client access after revocation");
    await assistant.locator("#clients-table-body .clients-link").first().waitFor({state:"detached"});
    ok(true,"revoked clients disappear from the visible directory");
    ok(errors.length===0,"no browser page errors");
    return {passed:checks.length,checks};
  }finally{for(const c of contexts)await c.close();}
}
